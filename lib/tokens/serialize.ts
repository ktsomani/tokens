import { COLOR_KEYS, type ColorKey, type Palette, type ThemeMode, type Tokens } from './schema'

/** camelCase token key → kebab CSS custom property name. */
export function cssVarName(key: ColorKey): string {
  return '--' + key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
}

export const TYPE_STEPS = ['xs', 'sm', 'base', 'lg', 'xl', '2xl', '3xl', '4xl'] as const
export type TypeStep = (typeof TYPE_STEPS)[number]

const STEP_EXPONENT: Record<TypeStep, number> = {
  xs: -2,
  sm: -1,
  base: 0,
  lg: 1,
  xl: 2,
  '2xl': 3,
  '3xl': 4,
  '4xl': 5,
}

const round = (n: number) => Math.round(n * 1000) / 1000

/** Modular scale, emitted in rem so it still honours the user's browser size. */
export function typeScaleSizes(tokens: Tokens): Record<TypeStep, string> {
  const out = {} as Record<TypeStep, string>
  for (const step of TYPE_STEPS) {
    const px = tokens.baseFontSize * Math.pow(tokens.typeScale, STEP_EXPONENT[step])
    out[step] = `${round(px / 16)}rem`
  }
  return out
}

export const SPACE_STEPS = [0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 16] as const

export function spacingSizes(tokens: Tokens): Record<string, string> {
  const out: Record<string, string> = {}
  for (const n of SPACE_STEPS) {
    out[String(n).replace('.', '_')] = `${round((n * tokens.spacingBase) / 16)}rem`
  }
  return out
}

/**
 * The entire bridge between the token panel and the live preview.
 * Changing any token produces a new map here; the difference is written
 * straight onto the iframe's documentElement. No React, no re-transpile.
 */
export function toCssVars(tokens: Tokens, mode: ThemeMode): Record<string, string> {
  const vars: Record<string, string> = {}
  const palette: Palette = tokens.colors[mode]

  for (const key of COLOR_KEYS) vars[cssVarName(key)] = palette[key]

  vars['--radius'] = `${tokens.radius}rem`
  vars['--font-sans'] = `"${tokens.fontFamily.sans}", ui-sans-serif, system-ui, sans-serif`
  vars['--font-mono'] = `"${tokens.fontFamily.mono}", ui-monospace, monospace`
  vars['--base-size'] = `${tokens.baseFontSize}px`
  vars['--space-unit'] = `${tokens.spacingBase}px`

  const sizes = typeScaleSizes(tokens)
  for (const step of TYPE_STEPS) vars[`--text-${step}`] = sizes[step]

  const spaces = spacingSizes(tokens)
  for (const [name, value] of Object.entries(spaces)) vars[`--space-${name}`] = value

  return vars
}

/** Export 1 — a CSS variables stylesheet covering both themes. */
export function toCssFile(tokens: Tokens): string {
  const block = (mode: ThemeMode) =>
    Object.entries(toCssVars(tokens, mode))
      .map(([k, v]) => `  ${k}: ${v};`)
      .join('\n')

  return `/* Generated by Tokens */

:root {
  color-scheme: light;
${block('light')}
}

.dark,
[data-theme='dark'] {
  color-scheme: dark;
${block('dark')}
}
`
}

/** Export 2 — a Tailwind config that reads those variables. */
export function toTailwindConfig(tokens: Tokens): string {
  const colors = COLOR_KEYS.map(
    (k) => `        ${k}: 'hsl(var(${cssVarName(k)}) / <alpha-value>)',`,
  ).join('\n')

  const fontSize = TYPE_STEPS.map((s) => `        '${s}': 'var(--text-${s})',`).join('\n')

  const spacing = Object.keys(spacingSizes(tokens))
    .map((n) => `        '${n.replace('_', '.')}': 'var(--space-${n})',`)
    .join('\n')

  return `/** Generated by Tokens — pair with the exported CSS variables. */
/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: ['class', '[data-theme="dark"]'],
  content: ['./src/**/*.{js,ts,jsx,tsx,mdx}'],
  theme: {
    extend: {
      colors: {
${colors}
      },
      borderRadius: {
        DEFAULT: 'var(--radius)',
        sm: 'calc(var(--radius) - 2px)',
        lg: 'calc(var(--radius) + 2px)',
      },
      fontFamily: {
        sans: ['var(--font-sans)'],
        mono: ['var(--font-mono)'],
      },
      fontSize: {
${fontSize}
      },
      spacing: {
${spacing}
      },
    },
  },
  plugins: [],
}
`
}

/** Export 3 — the component, as a drop-in file. */
export function toComponentFile(name: string, code: string): string {
  return `'use client'

import * as React from 'react'

${code}

export default ${name}
`
}

/** Export 4 — raw JSON, for pasting into another tool. */
export function toJsonFile(tokens: Tokens): string {
  return JSON.stringify(tokens, null, 2) + '\n'
}
